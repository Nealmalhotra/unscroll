#!/usr/bin/env bash
# One-time setup: picks your Apple Developer team, writes Config/Local.xcconfig
# and generates Unscroll.xcodeproj.
#
#   ./scripts/setup.sh                      # interactive
#   ./scripts/setup.sh --team ABCDE12345    # non-interactive
#   ./scripts/setup.sh --team ABCDE12345 --prefix com.me.unscroll --force
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LOCAL="$ROOT/Config/Local.xcconfig"
TEAM=""
PREFIX=""
FORCE=0

usage() { sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --team) TEAM="${2:-}"; shift 2 ;;
    --prefix) PREFIX="${2:-}"; shift 2 ;;
    --force) FORCE=1; shift ;;
    -h|--help) usage 0 ;;
    *) echo "Unknown option: $1" >&2; usage 1 ;;
  esac
done

if ! command -v xcodegen >/dev/null 2>&1; then
  if command -v brew >/dev/null 2>&1; then
    echo "Installing XcodeGen…"
    brew install xcodegen
  else
    echo "XcodeGen is required: https://github.com/yonaskolb/XcodeGen#installing" >&2
    exit 1
  fi
fi

# Lists "TEAMID<TAB>Team name" for paid teams signed into Xcode (free teams can't use Screen Time).
detect_teams() {
  defaults export com.apple.dt.Xcode - 2>/dev/null | python3 -I -c '
import plistlib, sys
try:
    prefs = plistlib.loads(sys.stdin.buffer.read())
except Exception:
    sys.exit(0)
seen = set()
for teams in prefs.get("IDEProvisioningTeamByIdentifier", {}).values():
    for team in teams:
        team_id = team.get("teamID")
        if team_id and not team.get("isFreeProvisioningTeam") and team_id not in seen:
            seen.add(team_id)
            print(team_id + "\t" + team.get("teamName", ""))
' || true
}

if [[ -f "$LOCAL" && $FORCE -eq 0 && -z "$TEAM" ]]; then
  echo "Using existing Config/Local.xcconfig (pass --force to recreate it)."
else
  if [[ -z "$TEAM" ]]; then
    TEAMS="$(detect_teams)"
    if [[ -n "$TEAMS" ]]; then
      echo "Paid teams signed into Xcode:"
      echo "$TEAMS" | awk -F'\t' '{printf "  %d) %s  %s\n", NR, $1, $2}'
      read -r -p "Pick a number, or paste a Team ID: " CHOICE
      if [[ "$CHOICE" =~ ^[0-9]+$ ]]; then
        TEAM="$(echo "$TEAMS" | sed -n "${CHOICE}p" | cut -f1)"
      else
        TEAM="$CHOICE"
      fi
    else
      echo "No paid team found in Xcode. Sign in under Xcode › Settings › Accounts,"
      echo "or paste your Team ID (developer.apple.com › Membership)."
      read -r -p "Team ID: " TEAM
    fi
  fi

  if [[ ! "$TEAM" =~ ^[A-Z0-9]{10}$ ]]; then
    echo "\"$TEAM\" doesn't look like a Team ID (10 letters/digits)." >&2
    exit 1
  fi

  # Default prefix is unique per team, so bundle IDs never collide with anyone else's.
  if [[ -z "$PREFIX" ]]; then
    PREFIX="com.$(echo "$TEAM" | tr '[:upper:]' '[:lower:]').unscroll"
  fi
  if [[ ! "$PREFIX" =~ ^[A-Za-z0-9]+(\.[A-Za-z0-9-]+)+$ ]]; then
    echo "\"$PREFIX\" isn't a valid bundle ID prefix (e.g. com.yourname.unscroll)." >&2
    exit 1
  fi

  cat > "$LOCAL" <<EOF
// Generated by scripts/setup.sh. Gitignored. Edit freely.
DEVELOPMENT_TEAM = $TEAM
BUNDLE_ID_PREFIX = $PREFIX
APP_GROUP = group.$PREFIX
EOF
  echo "Wrote Config/Local.xcconfig (team $TEAM, bundle IDs $PREFIX.*)."
fi

(cd "$ROOT" && xcodegen generate --quiet)
echo
echo "Done. Next: open Unscroll.xcodeproj, pick your iPhone and press Run."
